export function generateFullIndexMd(): string {
  const rows = PORTFOLIO_POSTS_REGISTRY.map((p) => {
    const link = `[[${p.slug}|${p.title}]]`;
    const mediumScale = p.dimensions && p.dimensions !== '-' ? `${p.medium} (${p.dimensions})` : p.medium;
    return `| ${link} | ${p.date} | ${p.status} | ${mediumScale} |`;
  }).join('\n');

  return `# Rory Skagen — Master Art Archive & Studio Catalog

This master index contains all verified artwork records and static informational pages for **Rory Skagen** (137 Portfolio Entries, 2 Informational Pages, and 174 Cloudinary Media Assets).

---

## 1. Informational Core Pages

- [[pages/about|About Rory Skagen]]
- [[pages/contact|Contact Information & Studio Inquiries]]

---

## 2. Portfolio Entries (Posts Archive)

| Portfolio Entry Link | Production Date | Status Classification | Medium & Scale |
|:---|:---|:---|:---|
${rows}

---

## 3. Media Assets & Verification Logs
The complete media inventory is cross-referenced with Cloudinary CDN storage (\`xjilp2pq\`) with active and archived deployment links.
`;
}

export function generateAllPostsRecord(): Record<string, string> {
  const map: Record<string, string> = {};

  for (const post of PORTFOLIO_POSTS_REGISTRY) {
    const yamlTags = post.tags.map((t) => `  - ${t}`).join('\n');
    const imageEmbed = post.image ? `![[${post.image}]]` : `![[art.svg]]`;

    const content = `---
title: "${post.title}"
slug: "${post.slug}"
date: "${post.date}"
status: "${post.status}"
medium: "${post.medium}"
dimensions: "${post.dimensions}"
dimensions_in: "${post.dimensionsInches}"
dimensions_cm: "${post.dimensionsCm}"
surface: "${post.surface}"
price: "${post.price}"
location: "${post.location}"
series: "${post.series}"
image: "${post.image}"
tags:
${yamlTags}
---

[[index|← Return to Master Catalog Index]]

# ${post.title}

${imageEmbed}

> **${post.series}** — Produced ${post.date}
> **Medium & Dimensions:** ${post.medium} (${post.dimensions}) • ${post.dimensionsInches} (${post.dimensionsCm})
> **Status:** ${post.status} • **Surface:** ${post.surface}

## Artwork Description

${post.description}
`;

    map[`${post.slug}.md`] = content;
  }

  return map;
}
